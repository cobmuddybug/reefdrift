#!/usr/bin/env node
// Rewrites selected web tests so they run against logic/reef.js instead of ES modules.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const WEB = process.env.REEF_WEB || path.join(process.env.HOME, 'Projects/reef-drift')
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../tests/ported')
const TESTS = (process.env.PORT_TESTS || 'rng species world sim behaviour soak save').split(' ')

fs.mkdirSync(OUT, { recursive: true })
for (const name of TESTS) {
  let src = fs.readFileSync(path.join(WEB, 'tests', name + '.test.js'), 'utf8')
  src = src.replace(/^import\s+\{([^}]*)\}\s+from\s+'\.\.\/src\/([^']+)\.js'\s*;?$/gm, (m, list, key) =>
    `const {${list.replace(/\s+as\s+/g, ': ')}} = Reef[${JSON.stringify(key)}]`)
  src = src.replace(/^import\s+\*\s+as\s+(\w+)\s+from\s+'\.\.\/src\/([^']+)\.js'\s*;?$/gm, (m, n, key) => `const ${n} = Reef[${JSON.stringify(key)}]`)
  if (/from\s+'\.\.\//.test(src)) throw new Error(name + ': imports something outside src/ (not portable): ' + src.match(/^.*from\s+'\.\.\/.*$/m)[0])
  src = src.replace(/(import test from 'node:test'\n)/, `$1import { Reef } from '../lib.mjs'\n`)
  fs.writeFileSync(path.join(OUT, name + '.test.js'), '// GENERATED by dev/tools/port-tests.mjs from the web repo. Do not edit.\n' + src)
}
console.log('ported ' + TESTS.join(' '))
