#!/usr/bin/env node
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawn, execFileSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { serve } from './audio/server.mjs'

const WEB = process.env.REEF_WEB || path.join(process.env.HOME, 'Projects/reef-drift')
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..')
// rendered WAVs are kept (git-ignored) so a re-encode (ENCODE_ONLY=1) does not need the 10-minute render
const TMP = path.join(ROOT, 'dev/tools/audio/out')
fs.mkdirSync(TMP, { recursive: true })
const { prepare } = await import(pathToFileURL(path.join(WEB, 'src/music.js')).href)
const { TRACK_DATA } = await import(pathToFileURL(path.join(WEB, 'src/music/tracks.js')).href)

const EAT_R = [0.7, 1.5, 2.5, 3.5, 5, 7, 9, 12, 16, 22]
const SFX_SECS = { flick: 2, scatter: 3, respawn: 4, warn: 2, dizzy: 1.5, whale: 8, fullgrown: 14, menu: 1, confirm: 3 }
const jobs = []
EAT_R.forEach((r, i) => jobs.push({ kind: 'sfx', name: 'eat', arg: r, secs: 1.5, out: `sfx/eat-${i}.wav` }))
for (const [name, secs] of Object.entries(SFX_SECS)) jobs.push({ kind: 'sfx', name, secs, out: `sfx/${name}.wav` })
for (let i = 0; i < 10; i++) jobs.push({ kind: 'bell', index: i, secs: 7, out: `sfx/chime-${i}.wav` })
for (const id of Object.keys(TRACK_DATA)) jobs.push({ kind: 'music', id, secs: Math.ceil(prepare(id).length + 9), out: `music/${id}.wav` })
const WASH = { bright: 700, mid: 400, deep: 130 }
for (const [k, freq] of Object.entries(WASH)) jobs.push({ kind: 'wash', freq, secs: 100, out: `loops/wash-${k}.wav` })

let srv, chrome, timer
if (process.env.ENCODE_ONLY) { finish(); process.exit(0) }
srv = serve({ web: WEB, jobs, outDir: TMP, onDone: () => finish() })
await new Promise((r) => srv.listen(0, '127.0.0.1', r))
const port = srv.address().port
chrome = spawn('chromium', ['--headless=new', '--no-sandbox', '--disable-gpu', '--autoplay-policy=no-user-gesture-required', `--user-data-dir=${fs.mkdtempSync(path.join(os.tmpdir(), 'reefbake-'))}`, `http://127.0.0.1:${port}/`], { stdio: 'ignore' })
timer = setTimeout(() => { console.error('bake timed out'); chrome.kill(); process.exit(1) }, 15 * 60 * 1000)

function finish() {
  if (timer) clearTimeout(timer); if (chrome) chrome.kill(); if (srv) srv.close()
  const manifest = { eat: [], sfx: {}, chimes: [], tracks: {}, wash: {} }
  for (const j of jobs) {
    // QSoundEffect only plays PCM, so the short effects stay WAV; music and the wash loops are Vorbis
    const pcm = j.kind === 'sfx' || j.kind === 'bell'
    const wav = path.join(TMP, j.out), rel = pcm ? j.out : j.out.replace(/\.wav$/, '.ogg'), dest = path.join(ROOT, 'sounds', rel)
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    // trim trailing silence (echo tails fade to nothing), then Vorbis; wash loops must not be trimmed
    const trim = j.kind === 'wash' ? [] : ['-af', 'areverse,silenceremove=start_periods=1:start_threshold=-90dB,areverse']
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, ...trim, ...(j.kind === 'wash' ? ['-ac', '1'] : []), ...(pcm ? ['-ac', '1', '-c:a', 'pcm_s16le'] : ['-c:a', 'libvorbis', '-q:a', j.kind === 'music' ? '4' : '5']), dest])
    if (j.name === 'eat') manifest.eat.push({ r: j.arg, file: rel })
    else if (j.kind === 'sfx') manifest.sfx[j.name] = rel
    else if (j.kind === 'bell') manifest.chimes.push(rel)
    else if (j.kind === 'music') manifest.tracks[j.id] = rel
    else manifest.wash[path.basename(rel, '.ogg').replace('wash-', '')] = rel
  }
  fs.writeFileSync(path.join(ROOT, 'ui/sounds.js'), `.pragma library
// GENERATED by dev/tools/bake-audio.mjs. Do not edit.
var EAT = ${JSON.stringify(manifest.eat)}
var SFX = ${JSON.stringify(manifest.sfx)}
var CHIMES = ${JSON.stringify(manifest.chimes)}
var TRACKS = ${JSON.stringify(manifest.tracks)}
var WASH = ${JSON.stringify(manifest.wash)}
var WASH_FREQ = ${JSON.stringify(WASH)}
function eatFile(r) {
  var best = EAT[0]
  for (var i = 1; i < EAT.length; ++i) if (Math.abs(EAT[i].r - r) < Math.abs(best.r - r)) best = EAT[i]
  return best.file
}
`)
  console.log(`baked ${jobs.length} audio files`)
}
