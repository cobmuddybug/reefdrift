#!/usr/bin/env node
// Bundles the web game's pure modules into logic/reef.js, a QML `.pragma library` exposing global `Reef`.
// Mechanical on purpose: nothing is rewritten by hand, so the plugin cannot drift from the web sim.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const WEB = process.env.REEF_WEB || path.join(process.env.HOME, 'Projects/reef-drift')
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../../logic/reef.js')
// dependency order
const MODULES = ['palette', 'rng', 'species', 'world', 'behaviour', 'spawner', 'sim', 'bot', 'fx', 'save', 'music/tracks', 'music']

const keyOf = (from, spec) => path.posix.normalize(path.posix.join(path.posix.dirname(from), spec)).replace(/\.js$/, '')

export function transform(key, src) {
  const names = []
  src = src.replace(/^import\s+\*\s+as\s+(\w+)\s+from\s+'([^']+)'\s*;?$/gm, (m, n, spec) => `const ${n} = __m[${JSON.stringify(keyOf(key + '.js', spec))}]`)
  src = src.replace(/^import\s+\{([^}]*)\}\s+from\s+'([^']+)'\s*;?$/gm, (m, list, spec) =>
    `const {${list.replace(/\s+as\s+/g, ': ')}} = __m[${JSON.stringify(keyOf(key + '.js', spec))}]`)
  if (/^import\s/m.test(src)) throw new Error(key + ': unhandled import form')
  src = src.replace(/^export\s+(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)/gm, (m, n) => { names.push(n); return m.replace(/^export\s+/, '') })
  src = src.replace(/^export\s*\{([^}]*)\}\s*;?$/gm, (m, list) => { list.split(',').map((s) => s.trim()).filter(Boolean).forEach((s) => names.push(s.split(/\s+as\s+/).pop())); return '' })
  if (/^export\s/m.test(src)) throw new Error(key + ': unhandled export form')
  // Qt's JS engine has no object spread: rewrite the forms the web code uses
  src = src.replace(/^(\s+)\.\.\.\{(.*)\},$/gm, (m, ind, inner) => `${ind}${inner},`)
  src = src.replace(/\{\s*\.\.\.(\w+)\s*\}/g, 'Object.assign({}, $1)')
  src = src.replace(/\{([^{}]*?),\s*\.\.\.(\w+),\s*([^{}]*?)\s*\}/g, 'Object.assign({$1}, $2, {$3})')
  src = src.replace(/\{([^{}]*?),\s*\.\.\.(\w+)\s*\}/g, 'Object.assign({$1}, $2)')
  src = src.replace(/\bcatch\s*\{/g, 'catch (_e) {') // optional catch binding is not safe in every Qt JS engine
  return `__m[${JSON.stringify(key)}] = (function () {\n${src}\nreturn { ${[...new Set(names)].join(', ')} }\n})()\n`
}

export function build() {
  let out = '.pragma library\n// GENERATED by dev/tools/bundle-logic.mjs from the web game. Do not edit.\n'
  // Qt's JS engine predates a few ES2019 builtins the web code uses
  out += `if (typeof Object.fromEntries !== 'function') Object.fromEntries = function (it) { var o = {}; for (var e of it) o[e[0]] = e[1]; return o }
if (typeof Array.prototype.flat !== 'function') Array.prototype.flat = function (d) { d = d === undefined ? 1 : d; return this.reduce(function (a, v) { return a.concat(Array.isArray(v) && d > 0 ? v.flat(d - 1) : v) }, []) }
if (typeof Array.prototype.flatMap !== 'function') Array.prototype.flatMap = function (f, t) { return this.map(f, t).flat(1) }
`
  out += 'var Reef = (function () {\nvar __m = {}\n'
  for (const key of MODULES) out += transform(key, fs.readFileSync(path.join(WEB, 'src', key + '.js'), 'utf8'))
  out += 'return __m\n})()\n'
  return out
}

if (process.argv[1] === fileURLToPath(import.meta.url)) { fs.writeFileSync(OUT, build()); console.log('wrote ' + path.relative(process.cwd(), OUT)) }
